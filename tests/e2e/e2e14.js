// Dalil Pi for merchants: landing page → register shop → appears in search.
const { chromium } = require('playwright');
const OUT = process.argv[2];
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 420, height: 900 }, extraHTTPHeaders: { 'x-vercel-ip-country': 'EG' }, geolocation: { latitude: 30.05, longitude: 31.24 }, permissions: ['geolocation'] });
  const p = await ctx.newPage();
  const errors = [];
  p.on('pageerror', (e) => errors.push(e.message));
  await p.goto('http://localhost:3100/merchants', { waitUntil: 'networkidle' });
  ok(/Dalil Pi for merchants/.test(await p.locator('main').innerText()) && /دليل باي للتجار/.test(await p.locator('main').innerText()), 'merchants page (EN + AR)');
  await p.screenshot({ path: `${OUT}/24-merchants.png` });
  await p.getByTestId('register-shop').click();
  await p.getByText('Dev sign-in (local only)').click();
  await p.getByTestId('tour').getByRole('button', { name: 'Skip' }).click({ timeout: 6000 }).catch(() => {});
  const shop = p.getByTestId('my-shop');
  await shop.waitFor({ timeout: 10000 });
  ok(true, '/?shop=1 opens "My shop" after sign-in');
  const inputs = shop.locator('input');
  await shop.locator('label', { hasText: 'Shop name' }).locator('input').fill('Pi Corner Cafe');
  await shop.locator('label', { hasText: 'City' }).locator('input').fill('Cairo');
  await shop.locator('label', { hasText: 'Phone' }).locator('input').fill('+20 100 222 3333');
  await shop.locator('label', { hasText: 'Street' }).locator('input').fill('3 Qasr El Nil St');
  await shop.getByText("Use my current location").click();
  await shop.getByText('Location saved').waitFor();
  await shop.locator('label', { hasText: 'What you sell' }).locator('input').fill('coffee, pastries');
  await shop.getByTestId('item-title').first().fill('Espresso coffee');
  await shop.getByTestId('item-price').first().fill('1.2');
  await shop.getByRole('button', { name: 'Send for review' }).click();
  await shop.getByTestId('shop-status').waitFor();
  ok(/Approved/.test(await shop.getByTestId('shop-status').innerText()), 'shop saved (auto-approve on in this test)');
  await p.screenshot({ path: `${OUT}/25-myshop.png` });
  await p.getByRole('dialog').getByRole('button', { name: 'Close' }).first().click();
  await p.waitForTimeout(600);
  ok(await p.getByTestId('home').isVisible(), 'after My shop: the new home page');
  await p.getByTestId('ask-fab').click();
  await p.getByRole('textbox', { name: 'What do you want to buy with Pi?' }).fill('MERCH coffee');
  await p.keyboard.press('Enter');
  await p.getByText('Merchants shown').waitFor({ timeout: 30000 });
  const card = p.locator('[data-offer-card][data-store="Pi Corner Cafe"]');
  const t = await card.innerText();
  ok(t.includes('Espresso coffee') && t.includes('1.2') && t.includes('3 Qasr El Nil St'), 'registered shop appears in search with its Pi price');
  ok(!t.includes('Price not confirmed'), 'merchant price counts as confirmed');
  ok((await card.getByRole('link', { name: 'Call' }).getAttribute('href')) === 'tel:+201002223333', 'call button');
  // invalid input is refused by the server
  const token = (await (await fetch('http://localhost:3100/api/auth/pi', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ dev: 'tester' }) })).json()).token;
  const bad = await fetch('http://localhost:3100/api/merchants/me', { method: 'PUT', headers: { Authorization: `Bearer ${token}`, 'content-type': 'application/json' }, body: JSON.stringify({ name: 'X Shop', kind: 'local', country: 'EG', website: 'javascript:alert(1)', items: [] }) });
  ok(bad.status === 400, `unsafe website refused (${bad.status})`);
  ok(errors.length === 0, `no page errors ${errors.join(' | ')}`);
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
